import { UR, UREncoder } from '@ngraveio/bc-ur';
import { act, create } from 'react-test-renderer';

import { QrScanner } from '../QrScanner';

import type { QrScannerComponentProps } from '../QrScanner';
import type { QrDetectedSymbol } from '../symbols';

type Wrapped<T> = { f: T };
interface NativeProps {
  active: boolean;
  onReady: Wrapped<(generation: number, cameraId: string) => void>;
  onFrameText: Wrapped<(text: string, generation: number) => void>;
  onFrameSymbols?: Wrapped<(symbols: QrDetectedSymbol[], generation: number) => void>;
  onError: Wrapped<(code: string, message: string, generation: number) => void>;
}

let nativeProps: NativeProps | undefined;

jest.mock('react-native-nitro-modules', () => ({
  callback: (f: unknown) => ({ f }),
  getHostComponent: () => (props: NativeProps) => {
    nativeProps = props;
    return null;
  },
}));
// Generated by nitrogen (gitignored); the mocked host never reads it.
jest.mock(
  '../../nitrogen/generated/shared/json/QrScannerConfig.json',
  () => ({}),
  { virtual: true }
);

function native(): NativeProps {
  if (!nativeProps) throw new Error('native view not rendered');
  return nativeProps;
}

/** A Pro-style animated code: a PSBT-sized payload in many fountain parts. */
function animatedParts(count: number, payloadBytes = 600, fragment = 60) {
  const body = Buffer.alloc(payloadBytes, 0x5a);
  const cbor = Buffer.concat([
    Buffer.from([0x59, payloadBytes >> 8, payloadBytes & 0xff]),
    body,
  ]);
  const encoder = new UREncoder(new UR(cbor, 'crypto-psbt'), fragment);
  return {
    cbor,
    parts: Array.from({ length: count }, () => encoder.nextPart().toUpperCase()),
  };
}

function renderScanner(props: Partial<QrScannerComponentProps> = {}) {
  const handlers = {
    onReady: jest.fn(),
    onProgress: jest.fn(),
    onResult: jest.fn(),
    onError: jest.fn(),
  };
  let renderer: ReturnType<typeof create> | undefined;
  act(() => {
    renderer = create(
      <QrScanner active mode="ur" {...handlers} {...props} />
    );
  });
  return { handlers, renderer: renderer! };
}

beforeEach(() => {
  nativeProps = undefined;
});

describe('QrScanner', () => {
  it('reports the bound camera for the current capture generation', () => {
    const { handlers } = renderScanner({ cameraId: 'disconnected-usb' });
    native().onReady.f(2, 'built-in-back');
    native().onReady.f(1, 'disconnected-usb');

    expect(handlers.onReady.mock.calls).toEqual([['built-in-back']]);
  });

  it('delivers queued camera readiness across a scan session reset', () => {
    const { handlers, renderer } = renderScanner({
      cameraId: 'disconnected-usb', mode: 'static', sessionKey: 'first',
    });
    const previous = native();
    act(() => renderer.update(
      <QrScanner active cameraId="disconnected-usb" mode="static" sessionKey="second" {...handlers} />
    ));

    previous.onReady.f(2, 'built-in-back');
    previous.onFrameText.f('previous QR', 2);
    previous.onError.f('camera-busy', 'previous error', 2);
    native().onFrameText.f('obsolete capture QR', 1);
    native().onFrameText.f('current QR', 2);

    expect(handlers.onReady.mock.calls).toEqual([['built-in-back']]);
    expect(native().onReady).toBe(previous.onReady);
    expect(handlers.onResult.mock.calls).toEqual([[{ kind: 'text', text: 'current QR' }]]);
    expect(handlers.onError).not.toHaveBeenCalled();
  });

  it('retires queued symbol and text callbacks across freeze without changing capture generation', () => {
    const onFrameSymbols = jest.fn();
    const { handlers, renderer } = renderScanner({ mode: 'static', onFrameSymbols });
    native().onReady.f(1, 'camera');
    const beforeFreeze = native();
    const oldSymbols = [{ text: 'old QR', centerX: 0.5, centerY: 0.5 }];

    act(() => renderer.update(
      <QrScanner active frozen mode="static" onFrameSymbols={onFrameSymbols} {...handlers} />
    ));
    beforeFreeze.onFrameSymbols?.f(oldSymbols, 1);
    beforeFreeze.onFrameText.f('old QR', 1);
    const frozenCallbacks = native();
    act(() => renderer.update(
      <QrScanner active mode="static" onFrameSymbols={onFrameSymbols} {...handlers} />
    ));
    beforeFreeze.onFrameSymbols?.f(oldSymbols, 1);
    beforeFreeze.onFrameText.f('old QR', 1);
    frozenCallbacks.onFrameText.f('old frozen QR', 1);
    expect(onFrameSymbols).not.toHaveBeenCalled();
    expect(handlers.onResult).not.toHaveBeenCalled();

    const currentSymbols = [{ ...oldSymbols[0]!, text: 'fresh QR' }];
    native().onFrameSymbols?.f(currentSymbols, 1);
    native().onFrameText.f('fresh QR', 1);
    expect(onFrameSymbols).toHaveBeenCalledWith(currentSymbols);
    expect(handlers.onResult).toHaveBeenCalledWith({ kind: 'text', text: 'fresh QR' });
  });

  it('delivers queued frames when frozen changes from omitted to false', () => {
    const onFrameSymbols = jest.fn();
    const { handlers, renderer } = renderScanner({ mode: 'static', onFrameSymbols });
    const beforeRender = native();
    act(() => renderer.update(
      <QrScanner active frozen={false} mode="static" onFrameSymbols={onFrameSymbols} {...handlers} />
    ));

    const symbols = [{ text: 'current QR', centerX: 0.5, centerY: 0.5 }];
    beforeRender.onFrameSymbols?.f(symbols, 1);
    beforeRender.onFrameText.f('current QR', 1);
    expect(onFrameSymbols).toHaveBeenCalledWith(symbols);
    expect(handlers.onResult).toHaveBeenCalledWith({ kind: 'text', text: 'current QR' });
  });

  it('drops queued readiness for a superseded camera selection', () => {
    const { handlers, renderer } = renderScanner({ cameraId: 'back' });
    const previousReady = native().onReady;
    act(() => renderer.update(<QrScanner active cameraId="front" mode="ur" {...handlers} />));

    previousReady.f(1, 'back');
    native().onReady.f(2, 'front');

    expect(handlers.onReady.mock.calls).toEqual([['front']]);
  });

  it('assembles an animated UR from a looping frame stream', () => {
    const { cbor, parts } = animatedParts(40);
    const { handlers } = renderScanner();
    native().onReady.f(1, 'back');

    // Each part seen on several consecutive frames, as a camera would.
    for (const part of parts) {
      for (let frame = 0; frame < 3; frame += 1) native().onFrameText.f(part, 1);
      if (handlers.onResult.mock.calls.length) break;
    }

    expect(handlers.onReady).toHaveBeenCalledTimes(1);
    expect(handlers.onResult).toHaveBeenCalledTimes(1);
    expect(handlers.onResult).toHaveBeenCalledWith({
      kind: 'ur',
      type: 'crypto-psbt',
      cbor: Uint8Array.from(cbor),
    });
    const progress = handlers.onProgress.mock.calls.map(([value]) => value);
    expect(progress.length).toBeGreaterThan(1);
    expect(progress.slice(0, -1).every((value) => value < 1)).toBe(true);
    expect(progress[progress.length - 1]).toBe(1);
    expect(handlers.onError).not.toHaveBeenCalled();

    // More frames after completion change nothing.
    native().onFrameText.f(parts[0]!, 1);
    expect(handlers.onResult).toHaveBeenCalledTimes(1);
  });

  it('keeps collected parts across a pause and drops stale generations', () => {
    const { parts } = animatedParts(40);
    const { handlers, renderer } = renderScanner();
    native().onFrameText.f(parts[0]!, 1);
    native().onFrameText.f(parts[1]!, 1);
    const before = handlers.onProgress.mock.calls.length;

    // Pause and resume: native starts generation 3.
    act(() => renderer.update(<QrScanner active={false} mode="ur" {...handlers} />));
    act(() => renderer.update(<QrScanner active mode="ur" {...handlers} />));
    native().onReady.f(3, 'back');

    // A late frame from generation 1 is dropped.
    native().onFrameText.f(parts[2]!, 1);
    expect(handlers.onProgress.mock.calls.length).toBe(before);

    // The same part in generation 3 counts, and parts from before the pause
    // are still there (the duplicate is ignored rather than restarting).
    native().onFrameText.f(parts[2]!, 3);
    native().onFrameText.f(parts[0]!, 3);
    expect(handlers.onProgress.mock.calls.length).toBe(before + 1);
  });

  it('drops a queued callback from the session before a pause and key change', () => {
    const { handlers, renderer } = renderScanner({ mode: 'static', sessionKey: 'first' });
    const previous = native();
    act(() => renderer.update(
      <QrScanner active={false} mode="static" sessionKey="second" {...handlers} />
    ));
    previous.onReady.f(1, 'back');
    previous.onFrameText.f('previous QR', 1);
    previous.onError.f('camera-busy', 'previous error', 1);
    expect(handlers.onReady).not.toHaveBeenCalled();
    expect(handlers.onResult).not.toHaveBeenCalled();
    expect(handlers.onError).not.toHaveBeenCalled();
    act(() => renderer.update(
      <QrScanner active mode="static" sessionKey="second" {...handlers} />
    ));
    previous.onReady.f(1, 'back');
    previous.onFrameText.f('previous QR', 1);
    native().onFrameText.f('current QR', 2);
    expect(handlers.onReady).not.toHaveBeenCalled();
    expect(handlers.onResult.mock.calls).toEqual([[{ kind: 'text', text: 'current QR' }]]);
  });

  it('starts a new session when sessionKey changes', () => {
    const { parts } = animatedParts(40);
    const { handlers, renderer } = renderScanner({ sessionKey: 'a' });
    native().onFrameText.f(parts[0]!, 1);
    act(() =>
      renderer.update(<QrScanner active mode="ur" sessionKey="b" {...handlers} />)
    );
    handlers.onProgress.mockClear();
    // Accepted again: the new session has no parts yet.
    native().onFrameText.f(parts[0]!, 1);
    expect(handlers.onProgress).toHaveBeenCalledTimes(1);
  });

  it('ignores another code in view while an animated code is half collected', () => {
    const { parts } = animatedParts(40);
    const { handlers } = renderScanner({ mode: 'auto' });
    native().onFrameText.f(parts[0]!, 1);
    native().onFrameText.f('https://example.com', 1);
    expect(handlers.onResult).not.toHaveBeenCalled();
  });

  it('reports a static code once in auto mode', () => {
    const { handlers } = renderScanner({ mode: 'auto' });
    native().onFrameText.f('lightning:LNBC1', 1);
    native().onFrameText.f('lightning:LNBC1', 1);
    expect(handlers.onResult).toHaveBeenCalledTimes(1);
    expect(handlers.onResult).toHaveBeenCalledWith({
      kind: 'text',
      text: 'lightning:LNBC1',
    });
  });

  it('reports UR limit errors and camera errors', () => {
    const { parts } = animatedParts(40, 600);
    const { handlers } = renderScanner({ limits: { maxMessageBytes: 100 } });
    native().onFrameText.f(parts[0]!, 1);
    expect(handlers.onError).toHaveBeenCalledWith(
      expect.objectContaining({ code: 'too-large' })
    );

    native().onError.f('permission-denied', 'denied', 1);
    native().onError.f('something-new', 'odd', 1);
    native().onError.f('camera-busy', 'late', 0);
    const codes = handlers.onError.mock.calls.map(([error]) => error.code);
    expect(codes).toEqual(['too-large', 'permission-denied', 'decoder-unavailable']);
  });
});
